//! Build script: bake the bundled maps and the build identity into the crate.
//!
//! The map documents in `data/maps/` are parsed and validated here, by the very
//! code the engine uses at run time (`src/geo.rs` is compiled into this script),
//! and written out as static tables. The engine then starts without parsing
//! JSON, and an invalid bundled map is a build error.

#![allow(unexpected_cfgs)]

use std::path::{Path, PathBuf};
use std::process::Command;
use std::{env, fs};

#[allow(dead_code, unused_imports)]
#[path = "src/rulebook.rs"]
mod rulebook;

#[allow(dead_code, unused_imports)]
#[path = "src/geo.rs"]
mod geo;

const MAPS: &[(&str, &str)] = &[("STANDARD", "standard"), ("DUEL", "duel")];

fn main() {
    println!("cargo:rustc-check-cfg=cfg(cabal_generated_maps)");
    println!("cargo:rustc-cfg=cabal_generated_maps");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/geo.rs");
    println!("cargo:rerun-if-changed=src/rulebook.rs");

    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let out = PathBuf::from(env::var("OUT_DIR").expect("out dir"));

    let mut source = String::from("// Generated by build.rs from data/maps. Do not edit.\n\n");
    for (constant, name) in MAPS {
        let path = manifest.join("data/maps").join(format!("{name}.json"));
        println!("cargo:rerun-if-changed={}", path.display());
        let json = fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
        let map = geo::Map::from_json(&json)
            .unwrap_or_else(|e| panic!("{} is not a valid map: {e}", path.display()));
        source.push_str(&map.to_tables_source(constant));
        source.push('\n');
    }
    fs::write(out.join("bundled_maps.rs"), source).expect("write bundled maps");

    build_identity(&manifest);
}

/// Record what was built: commit, profile, optimisation level and target.
/// `CABAL_BUILD_COMMIT` overrides the commit for builds outside a checkout.
fn build_identity(manifest: &Path) {
    println!("cargo:rerun-if-env-changed=CABAL_BUILD_COMMIT");
    let git = |args: &[&str]| -> Option<String> {
        let output = Command::new("git")
            .args(args)
            .current_dir(manifest)
            .output()
            .ok()?;
        output
            .status
            .success()
            .then(|| String::from_utf8_lossy(&output.stdout).trim().to_string())
            .filter(|s| !s.is_empty())
    };
    let commit = env::var("CABAL_BUILD_COMMIT")
        .ok()
        .filter(|s| !s.is_empty())
        .or_else(|| git(&["rev-parse", "--short=12", "HEAD"]))
        .unwrap_or_else(|| "unknown".to_string());
    // rebuild when the checkout moves to another commit
    for args in [
        ["rev-parse", "--git-path", "HEAD"],
        ["rev-parse", "--git-path", "packed-refs"],
    ] {
        if let Some(path) = git(&args) {
            println!("cargo:rerun-if-changed={}", manifest.join(path).display());
        }
    }
    if let Some(reference) = git(&["symbolic-ref", "-q", "HEAD"]) {
        if let Some(path) = git(&["rev-parse", "--git-path", &reference]) {
            println!("cargo:rerun-if-changed={}", manifest.join(path).display());
        }
    }
    println!("cargo:rustc-env=CABAL_BUILD_COMMIT={commit}");
    // Cargo's `PROFILE` only says `debug` or `release`, also for a profile
    // that inherits from one of them. The directory the build writes to is
    // named after the profile itself (`wasm-release`), three levels above
    // `OUT_DIR` (`<profile>/build/<crate>-<hash>/out`).
    let profile = env::var("OUT_DIR")
        .ok()
        .and_then(|out| {
            let name = Path::new(&out).ancestors().nth(3)?.file_name()?;
            Some(name.to_string_lossy().into_owned())
        })
        .or_else(|| env::var("PROFILE").ok())
        .unwrap_or_else(|| "unknown".to_string());
    println!("cargo:rustc-env=CABAL_BUILD_PROFILE={profile}");
    for (key, var) in [
        ("CABAL_BUILD_OPT_LEVEL", "OPT_LEVEL"),
        ("CABAL_BUILD_TARGET", "TARGET"),
    ] {
        let value = env::var(var).unwrap_or_else(|_| "unknown".to_string());
        println!("cargo:rustc-env={key}={value}");
    }
}
